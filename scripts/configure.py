"""Generate the browser settings from the same file the journal uses."""

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "config/family.json"
OUTPUT = ROOT / "web/family-config.js"


def read_config():
    config = json.loads(SOURCE.read_text(encoding="utf-8"))
    profiles = config["profiles"]
    if (
        not isinstance(profiles, list) or len(profiles) != 3
        or any(not isinstance(name, str) or not name.strip() or len(name) > 24 for name in profiles)
        or len({name.strip().casefold() for name in profiles}) != 3
    ):
        raise ValueError("profiles must contain three distinct names of 1–24 characters")
    offset = config["utcOffsetMinutes"]
    if type(offset) is not int or not -720 <= offset <= 840:
        raise ValueError("utcOffsetMinutes must be an integer between -720 and 840")
    goal = config["goal"]
    for key in ("title", "reward"):
        if not isinstance(goal[key], str) or not goal[key].strip() or len(goal[key]) > 80:
            raise ValueError(f"goal.{key} must contain 1–80 characters")
    for key, minimum, maximum in (("points", 1, 50), ("days", 1, 30)):
        if type(goal[key]) is not int or not minimum <= goal[key] <= maximum:
            raise ValueError(f"goal.{key} must be an integer between {minimum} and {maximum}")
    if type(goal["allowOneSkip"]) is not bool:
        raise ValueError("goal.allowOneSkip must be true or false")
    return config


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify generated browser settings")
    args = parser.parse_args()
    config = json.dumps(read_config(), ensure_ascii=True, indent=2)
    content = "// Generated by scripts/configure.py. Edit config/family.json.\nwindow.FamilyConfig = " + config + ";\n"
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != content:
            parser.exit(1, "Run python3 scripts/configure.py to regenerate browser settings.\n")
    else:
        OUTPUT.write_text(content, encoding="utf-8")


if __name__ == "__main__":
    main()
