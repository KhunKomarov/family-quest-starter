"""Validation shared by the setup wizard, journal and build script."""

import json


def validate_config(config):
    if not isinstance(config, dict):
        raise ValueError('invalid family configuration')
    profiles = config.get('profiles')
    if (not isinstance(profiles, list) or not 1 <= len(profiles) <= 6
            or any(not isinstance(name, str) or not name.strip() or len(name.strip()) > 24 for name in profiles)
            or len({name.strip().casefold() for name in profiles}) != len(profiles)):
        raise ValueError('profiles must contain 1–6 distinct names of 1–24 characters')
    offset = config.get('utcOffsetMinutes')
    if type(offset) is not int or not -720 <= offset <= 840:
        raise ValueError('utcOffsetMinutes must be an integer between -720 and 840')
    goal = config.get('goal')
    if not isinstance(goal, dict):
        raise ValueError('goal is required')
    for key in ('title', 'reward'):
        if not isinstance(goal.get(key), str) or not goal[key].strip() or len(goal[key].strip()) > 80:
            raise ValueError(f'goal.{key} must contain 1–80 characters')
    for key, minimum, maximum in (('points', 1, 50), ('days', 1, 30)):
        if type(goal.get(key)) is not int or not minimum <= goal[key] <= maximum:
            raise ValueError(f'goal.{key} must be an integer between {minimum} and {maximum}')
    if type(goal.get('allowOneSkip')) is not bool:
        raise ValueError('goal.allowOneSkip must be true or false')
    return {'profiles': [name.strip() for name in profiles], 'utcOffsetMinutes': offset,
            'goal': {key: value.strip() if isinstance(value, str) else value for key, value in goal.items()
                     if key in ('title', 'reward', 'points', 'days', 'allowOneSkip')}}


def browser_config(config):
    return '// Generated by scripts/configure.py. Edit config/family.json.\nwindow.FamilyConfig = ' + json.dumps(
        config, ensure_ascii=True, indent=2) + ';\n'


def validate_catalog(catalog, count):
    if not isinstance(catalog, list) or not catalog or len(catalog) > 100:
        raise ValueError('catalog must contain 1–100 dated menu sets')
    import re
    previous = -1
    for since, menus in catalog:
        if type(since) is not int or since <= previous or not isinstance(menus, list) or len(menus) != count:
            raise ValueError('catalog needs ascending days and one menu for each child')
        previous = since
        for menu in menus:
            if not isinstance(menu, dict):
                raise ValueError('invalid menu')
            for section in ('morning', 'afternoon', 'rewards'):
                tasks = menu.get(section)
                if not isinstance(tasks, list) or len(tasks) > 100:
                    raise ValueError('each section needs at most 100 tasks')
                identifiers = set()
                for task in tasks:
                    size = 3 if section == 'rewards' else 2
                    if not isinstance(task, list) or len(task) != size:
                        raise ValueError('invalid task')
                    identifier, title = task[:2]
                    if (not isinstance(identifier, str) or not re.fullmatch(r'[a-z0-9-]{1,60}', identifier)
                            or identifier in identifiers or not isinstance(title, str) or not 1 <= len(title.strip()) <= 180):
                        raise ValueError('invalid task identifier or title')
                    identifiers.add(identifier)
                    if size == 3 and (type(task[2]) is not int or not 1 <= task[2] <= 120):
                        raise ValueError('invalid reward rate')
                if section == 'morning' and identifiers != {'bed', 'teeth', 'dress', 'breakfast', 'car'}:
                    raise ValueError('keep the five required morning IDs')
            video = menu.get('video')
            if (not isinstance(video, dict) or not isinstance(video.get('title'), str)
                    or not 1 <= len(video['title'].strip()) <= 180
                    or any(type(video.get(key)) is not int or not 0 <= video[key] <= 120 for key in ('minutes', 'bats'))):
                raise ValueError('invalid repeatable creative task')
            if type(menu.get('afternoonMinutes', 5)) is not int or not 1 <= menu.get('afternoonMinutes', 5) <= 120:
                raise ValueError('invalid daytime rate')
    return catalog
